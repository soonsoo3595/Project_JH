#pragma once

#include "Core/Types.h"

// SC_ 접두사와 대문자 스네이크 표기를 사용한다.
// 성공은 0이며 나머지 값은 선언 순서대로 자동 부여한다. 종류별 번호 대역은 두지 않는다.
enum class StatusCode : int32
{
	SC_SUCCESS = 0,

	// 로그
	SC_LOG_INVALID_LEVEL,
	SC_LOG_INVALID_OUTPUT,
	SC_LOG_EMPTY_FILE_PATH,
	SC_LOG_DIRECTORY_CREATION_FAILED,
	SC_LOG_FILE_OPEN_FAILED,

	// 네트워크
	SC_NET_INVALID_ADDRESS,
	SC_NET_INVALID_SOCKET,
	SC_NET_SOCKET_ALREADY_OPEN,
	SC_NET_SOCKET_CREATE_FAILED,
	SC_NET_SOCKET_OPTION_FAILED,
	SC_NET_BIND_FAILED,
	SC_NET_LISTEN_FAILED,
	SC_NET_SOCKET_CLOSE_FAILED,
	SC_NET_LOCAL_ADDRESS_FAILED,
	SC_NET_INVALID_ARGUMENT,

	// IOCP
	SC_IOCP_NOT_INITIALIZED,
	SC_IOCP_ALREADY_INITIALIZED,
	SC_IOCP_CREATE_FAILED,
	SC_IOCP_REGISTER_FAILED,
	SC_IOCP_WAIT_TIMEOUT,
	SC_IOCP_WAIT_FAILED,
	SC_IOCP_IO_FAILED,
	SC_IOCP_POST_FAILED,
	SC_IOCP_CLOSE_FAILED,
	SC_IOCP_INVALID_OBJECT
};

const char* GetStatusMessage(StatusCode code) noexcept;
